class PackageError(RuntimeError):
    """A deterministic packaging or verification invariant failed."""


def fail(message: str) -> None:
    raise PackageError(message)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while True:
            chunk = stream.read(1024 * 1024)
            if not chunk:
                return digest.hexdigest()
            digest.update(chunk)


def safe_dependency_name(name: str) -> str:
    if not name or PurePosixPath(name).name != name or name in {".", ".."}:
        fail(f"unsafe DT_NEEDED name: {name!r}")
    if "\\" in name or "\x00" in name:
        fail(f"unsafe DT_NEEDED name: {name!r}")
    return name


@dataclass(frozen=True)
class ProgramHeader:
    kind: int
    offset: int
    vaddr: int
    filesz: int


@dataclass(frozen=True)
class ElfInfo:
    path: Path
    bits: int
    encoding: int
    endian: str
    machine: int
    interpreter: str | None
    interpreter_offset: int | None
    interpreter_size: int | None
    needed: tuple[str, ...]
    soname: str | None
    rpath: str | None
    runpath: str | None


def unpack(data: bytes, endian: str, fmt: str, offset: int) -> tuple[int, ...]:
    size = struct.calcsize(endian + fmt)
    if offset < 0 or offset + size > len(data):
        fail(f"truncated ELF structure at {offset:#x}")
    return struct.unpack_from(endian + fmt, data, offset)


def c_string(table: bytes, offset: int, description: str) -> str:
    if offset < 0 or offset >= len(table):
        fail(f"invalid {description} string offset {offset:#x}")
    end = table.find(b"\x00", offset)
    if end < 0:
        fail(f"unterminated {description} string")
    try:
        return table[offset:end].decode("ascii")
    except UnicodeDecodeError as exc:
        raise PackageError(f"non-ASCII {description} string") from exc


def parse_elf(path: Path) -> ElfInfo:
    try:
        data = path.read_bytes()
    except OSError as exc:
        raise PackageError(f"cannot read {path}: {exc}") from exc
    if data[:4] != b"\x7fELF":
        fail(f"not an ELF file: {path}")
    elf_class, encoding = data[4], data[5]
    if elf_class not in (1, 2) or encoding not in (1, 2):
        fail(f"unsupported ELF class/encoding: {path}")
    bits = 32 if elf_class == 1 else 64
    endian = "<" if encoding == 1 else ">"
    if bits == 64:
        header = unpack(data, endian, "HHIQQQIHHHHHH", 16)
        phoff, phentsize, phnum = header[4], header[8], header[9]
        ph_format = "IIQQQQQQ"
    else:
        header = unpack(data, endian, "HHIIIIIHHHHHH", 16)
        phoff, phentsize, phnum = header[4], header[8], header[9]
        ph_format = "IIIIIIII"
    machine = header[1]

    headers: list[ProgramHeader] = []
    interpreter_rows: list[tuple[int, int]] = []
    for number in range(phnum):
        row_offset = phoff + number * phentsize
        values = unpack(data, endian, ph_format, row_offset)
        if bits == 64:
            kind, file_offset, vaddr, filesz = values[0], values[2], values[3], values[5]
        else:
            kind, file_offset, vaddr, filesz = values[0], values[1], values[2], values[4]
        if file_offset + filesz > len(data):
            fail(f"program header exceeds file: {path}")
        headers.append(ProgramHeader(kind, file_offset, vaddr, filesz))
        if kind == PT_INTERP:
            interpreter_rows.append((file_offset, filesz))
    if len(interpreter_rows) > 1:
        fail(f"multiple PT_INTERP segments: {path}")

    interpreter = None
    interpreter_offset = None
    interpreter_size = None
    if interpreter_rows:
        interpreter_offset, interpreter_size = interpreter_rows[0]
        segment = data[interpreter_offset : interpreter_offset + interpreter_size]
        if not segment.endswith(b"\x00"):
            fail(f"PT_INTERP is not NUL-terminated: {path}")
        try:
            interpreter = segment.split(b"\x00", 1)[0].decode("ascii")
        except UnicodeDecodeError as exc:
            raise PackageError(f"non-ASCII PT_INTERP: {path}") from exc

    def vaddr_to_offset(address: int) -> int:
        for ph in headers:
            if ph.kind != PT_LOAD:
                continue
            if ph.vaddr <= address < ph.vaddr + ph.filesz:
                return ph.offset + address - ph.vaddr
        fail(f"dynamic string table is not file-backed: {path}")
        raise AssertionError("unreachable")

    dynamic: list[tuple[int, int]] = []
    dynamic_size = 16 if bits == 64 else 8
    dynamic_format = "qQ" if bits == 64 else "iI"
    for ph in headers:
        if ph.kind != PT_DYNAMIC:
            continue
        if ph.filesz % dynamic_size:
            fail(f"misaligned PT_DYNAMIC segment: {path}")
        for offset in range(ph.offset, ph.offset + ph.filesz, dynamic_size):
            tag, value = unpack(data, endian, dynamic_format, offset)
            if tag == DT_NULL:
                break
            dynamic.append((tag, value))
    by_tag: dict[int, list[int]] = defaultdict(list)
    for tag, value in dynamic:
        by_tag[tag].append(value)
    string_table = b""
    if dynamic:
        if DT_STRTAB not in by_tag or DT_STRSZ not in by_tag:
            fail(f"dynamic ELF has no complete string table: {path}")
        string_offset = vaddr_to_offset(by_tag[DT_STRTAB][0])
        string_size = by_tag[DT_STRSZ][0]
        if string_offset + string_size > len(data):
            fail(f"dynamic string table exceeds file: {path}")
        string_table = data[string_offset : string_offset + string_size]

    def first_string(tag: int, description: str) -> str | None:
        values = by_tag.get(tag, [])
        if not values:
            return None
        if len(values) != 1:
            fail(f"multiple {description} entries: {path}")
        return c_string(string_table, values[0], description)

    needed = tuple(
        safe_dependency_name(c_string(string_table, value, "DT_NEEDED"))
        for value in by_tag.get(DT_NEEDED, [])
    )
    return ElfInfo(
        path=path,
        bits=bits,
        encoding=encoding,
        endian=endian,
        machine=machine,
        interpreter=interpreter,
        interpreter_offset=interpreter_offset,
        interpreter_size=interpreter_size,
        needed=needed,
        soname=first_string(DT_SONAME, "DT_SONAME"),
        rpath=first_string(DT_RPATH, "DT_RPATH"),
        runpath=first_string(DT_RUNPATH, "DT_RUNPATH"),
    )


def patch_interpreter(path: Path, elf: ElfInfo) -> tuple[bytes, dict[str, object]]:
    if elf.interpreter != "/system/bin/linker64":
        fail(f"unexpected keystore2 PT_INTERP: {elf.interpreter!r}")
    if elf.interpreter_offset is None or elf.interpreter_size is None:
        fail("keystore2 has no PT_INTERP")
    source = path.read_bytes()
    replacement = PRIVATE_INTERPRETER.encode("ascii") + b"\x00"
    if len(replacement) > elf.interpreter_size:
        fail("private PT_INTERP does not fit the source segment")
    offset, size = elf.interpreter_offset, elf.interpreter_size
    patched = bytearray(source)
    patched[offset : offset + size] = replacement + b"\x00" * (size - len(replacement))
    if patched[:offset] != source[:offset] or patched[offset + size :] != source[offset + size :]:
        fail("bytes outside PT_INTERP changed")
    return bytes(patched), {
        "original_interpreter": elf.interpreter,
        "private_interpreter": PRIVATE_INTERPRETER,
        "pt_interp_offset": offset,
        "pt_interp_size": size,
        "source_sha256": sha256(source),
        "output_sha256": sha256(bytes(patched)),
        "bytes_outside_pt_interp_unchanged": True,
    }


@dataclass
class SelectedLibrary:
    needed_name: str
    source_relative: str
    source_path: Path
    elf: ElfInfo
    requested_by: set[str]
    alternatives: tuple[str, ...]


def iter_library_candidates(root: Path):
    for priority, relative_directory in enumerate(LIBRARY_DIRECTORIES):
        directory = root / PurePosixPath(relative_directory)
        try:
            is_directory = directory.is_dir()
        except OSError:
            # CPIO extraction on Windows can materialize Linux directory
            # symlinks which the host cannot follow.  Canonical directories
            # earlier in LIBRARY_DIRECTORIES remain independently auditable.
            is_directory = False
        if not is_directory:
            continue
        try:
            paths = sorted(directory.rglob("*"), key=lambda item: item.as_posix())
        except OSError as exc:
            raise PackageError(f"cannot enumerate library directory {directory}: {exc}") from exc
        for path in paths:
            try:
                is_file = path.is_file()
            except OSError:
                is_file = False
            if not is_file:
                continue
            try:
                with path.open("rb") as stream:
                    if stream.read(4) != b"\x7fELF":
                        continue
                elf = parse_elf(path)
            except OSError as exc:
                raise PackageError(f"cannot inspect {path}: {exc}") from exc
            yield priority, path.relative_to(root).as_posix(), path, elf


def resolve_closure(root: Path, executable: ElfInfo) -> dict[str, SelectedLibrary]:
    index: dict[str, list[tuple[int, str, Path, ElfInfo]]] = defaultdict(list)
    for row in iter_library_candidates(root):
        priority, relative, path, elf = row
        index[path.name].append(row)
        if elf.soname and elf.soname != path.name:
            index[elf.soname].append(row)
    for rows in index.values():
        rows.sort(key=lambda row: (row[0], len(row[1]), row[1]))

    selected: dict[str, SelectedLibrary] = {}
    queue = deque((name, SOURCE_EXECUTABLE) for name in executable.needed)
    while queue:
        name, requester = queue.popleft()
        safe_dependency_name(name)
        if name in selected:
            selected[name].requested_by.add(requester)
            continue
        candidates = index.get(name, [])
        if not candidates:
            fail(f"missing DT_NEEDED {name!r}, requested by {requester}")
        minimum_priority = candidates[0][0]
        peers = [row for row in candidates if row[0] == minimum_priority]
        peer_hashes = {file_sha256(row[2]) for row in peers}
        if len(peer_hashes) != 1:
            fail(
                f"ambiguous same-priority candidates for {name!r}: "
                + ", ".join(row[1] for row in peers)
            )
        priority, relative, path, elf = peers[0]
        del priority
        if elf.bits != executable.bits or elf.encoding != executable.encoding or elf.machine != executable.machine:
            fail(f"ABI mismatch for {name!r}: {relative}")
        if elf.interpreter is not None:
            fail(f"DT_NEEDED candidate unexpectedly has PT_INTERP: {relative}")
        alternatives = tuple(row[1] for row in candidates[1:])
        selected[name] = SelectedLibrary(name, relative, path, elf, {requester}, alternatives)
        for child in elf.needed:
            queue.append((child, name))
    return selected


def write_file(path: Path, data: bytes, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    try:
        path.chmod(mode)
    except OSError as exc:
        raise PackageError(f"cannot set mode on {path}: {exc}") from exc


def validate_vintf(data: bytes) -> None:
    try:
        root = ET.fromstring(data)
    except ET.ParseError as exc:
        raise PackageError(f"invalid keystore2 VINTF fragment: {exc}") from exc
    if root.tag != "manifest" or root.attrib.get("type") != "framework":
        fail("keystore2 VINTF fragment is not a framework manifest")
    found = False
    for hal in root.findall("hal"):
        if hal.attrib.get("format") != "aidl" or hal.findtext("name") != "android.system.keystore2":
            continue
        for interface in hal.findall("interface"):
            if interface.findtext("name") != "IKeystoreService":
                continue
            if any(instance.text == "default" for instance in interface.findall("instance")):
                found = True
    if not found:
        fail("VINTF fragment lacks android.system.keystore2.IKeystoreService/default")


def copy_vintf(root: Path, install_root: Path) -> dict[str, object]:
    for candidate in VINTF_CANDIDATES:
        source = root / PurePosixPath(candidate)
        if source.is_file():
            data = source.read_bytes()
            validate_vintf(data)
            target = install_root / PurePosixPath(TARGET_VINTF)
            write_file(target, data, 0o644)
            return {
                "source": candidate,
                "target": TARGET_VINTF,
                "bytes": len(data),
                "sha256": sha256(data),
            }
    fail("keystore2 VINTF fragment is missing from recovery root")
    raise AssertionError("unreachable")


def write_reference_contexts(root: Path, output: Path) -> list[dict[str, object]]:
    reference_root = output / "reference-contexts"
    write_file(reference_root / "README.txt", REFERENCE_README.encode("utf-8"), 0o644)
    records = []
    for relative, pattern in REFERENCE_CONTEXT_SPECS:
        source = root / PurePosixPath(relative)
        if not source.is_file():
            continue
        text = source.read_text(encoding="utf-8", errors="strict")
        if pattern is None:
            selected_lines = text.splitlines()
        else:
            matcher = re.compile(pattern, re.IGNORECASE)
            selected_lines = [line for line in text.splitlines() if matcher.search(line)]
        if not selected_lines:
            continue
        data = ("\n".join(selected_lines) + "\n").encode("utf-8")
        target_name = relative.replace("/", "__") + ".reference.txt"
        target = reference_root / target_name
        write_file(target, data, 0o644)
        records.append(
            {
                "source": relative,
                "target": f"reference-contexts/{target_name}",
                "lines": len(selected_lines),
                "bytes": len(data),
                "sha256": sha256(data),
                "install": False,
            }
        )
    if not records:
        fail("no keystore2-related context reference material found")
    return records


