def listed_files(root: Path, exclude: set[str] | None = None) -> list[dict[str, object]]:
    excluded = exclude or set()
    rows = []
    for path in sorted((item for item in root.rglob("*") if item.is_file()), key=lambda item: item.as_posix()):
        relative = path.relative_to(root).as_posix()
        if relative in excluded:
            continue
        rows.append(
            {
                "path": relative,
                "bytes": path.stat().st_size,
                "sha256": file_sha256(path),
            }
        )
    return rows


def normalize_mtimes(root: Path, epoch: int) -> None:
    for path in sorted(root.rglob("*"), key=lambda item: item.as_posix(), reverse=True):
        if path.is_dir():
            path.chmod(0o755)
        # The output contains no symlinks.  Avoid follow_symlinks=False because
        # the bundled Windows Python runtime does not implement that variant.
        os.utime(path, (epoch, epoch))
    root.chmod(0o755)
    os.utime(root, (epoch, epoch))


def verify_service(data: str) -> None:
    expected_init = "on init\n    mkdir /tmp/misc\n    mkdir /tmp/misc/keystore/\n"
    expected_header = "service keystore2 /system/tw/bin/keystore2 /tmp/misc/keystore"
    if expected_header not in data:
        fail("private keystore2 service header is wrong")
    if data.count(expected_init) != 1 or data.index(expected_init) > data.index(expected_header):
        fail("private keystore2 database-directory init action is missing or misplaced")
    stanza = data.split(expected_header, 1)[1]
    if not re.search(r"(?m)^\s+disabled\s*$", stanza):
        fail("private keystore2 service is not disabled")
    if not re.search(r"(?m)^\s+seclabel u:r:recovery:s0\s*$", stanza):
        fail("private keystore2 service does not use recovery seclabel")
    if re.findall(r"(?m)^\s*on\s+.*$", data) != ["on init"]:
        fail("private keystore2 init fragment has an unexpected trigger")
    if re.search(r"(?m)^\s*start\s+keystore2\s*$", data):
        fail("private keystore2 service has a forbidden automatic start trigger")


def verify_context_shim(output: Path, manifest: dict[str, object]) -> None:
    shim_root = output / "context-shim"
    expected = {
        "README.txt": CONTEXT_SHIM_README.encode("utf-8"),
        "REQUIRES.txt": CONTEXT_SHIM_REQUIREMENT.encode("utf-8"),
        "plat_service_contexts.merge": SERVICE_CONTEXT_SHIM.encode("utf-8"),
        "plat_keystore2_key_contexts.merge": KEY_CONTEXT_SHIM.encode("utf-8"),
    }
    if not shim_root.is_dir():
        fail("installable compatibility context shim is missing")
    actual_names = sorted(path.name for path in shim_root.iterdir() if path.is_file())
    if actual_names != sorted(expected):
        fail(f"context shim file set is not exact: {actual_names}")
    for name, data in expected.items():
        path = shim_root / name
        if path.read_bytes() != data:
            fail(f"context shim content mismatch: {name}")
        # chmod has only a read-only-bit model on Windows.  CI/repack runs on
        # Linux, where the exact emitted mode is enforced here.
        if os.name == "posix" and (path.stat().st_mode & 0o7777) != 0o644:
            fail(f"context shim mode is not 0644: {name}")

    service_rows = [line.split() for line in SERVICE_CONTEXT_SHIM.splitlines() if line.strip()]
    if [row[0] for row in service_rows] != list(KEYSTORE2_BINDER_SERVICES):
        fail("context shim Binder service set/order changed")
    if any(len(row) != 2 or row[1] != STOCK_COMPATIBILITY_CONTEXT for row in service_rows):
        fail("context shim uses a non-stock Binder label")
    key_rows = [line.split() for line in KEY_CONTEXT_SHIM.splitlines() if line.strip()]
    if key_rows != [["103", STOCK_COMPATIBILITY_CONTEXT]]:
        fail("context shim is not the exact namespace-103 mapping")

    shim_manifest = manifest.get("compatibility_context_shim")
    if not isinstance(shim_manifest, dict) or shim_manifest.get("install") is not True:
        fail("manifest does not mark compatibility context shim installable")
    dependency = shim_manifest.get("required_companion_patch")
    if not isinstance(dependency, dict):
        fail("context shim companion-patch dependency is missing")
    if (
        dependency.get("source_marker") != COMPANION_PERMISSION_PATCH
        or dependency.get("pinned_source_commit") != PINNED_KEYSTORE2_SOURCE_COMMIT
        or dependency.get("mandatory") is not True
    ):
        fail("context shim companion-patch dependency is not exact/mandatory")
    operations = shim_manifest.get("operations")
    if not isinstance(operations, list) or len(operations) != 2:
        fail("context shim must have exactly two merge operations")
    expected_targets = [SERVICE_CONTEXT_TARGET, KEY_CONTEXT_TARGET]
    if [row.get("target") for row in operations] != expected_targets:
        fail("context shim merge targets changed")
    if any(row.get("mode") != "0644" for row in operations):
        fail("context shim target mode is not exactly 0644")

    serialized = SERVICE_CONTEXT_SHIM + KEY_CONTEXT_SHIM
    forbidden_types = (
        "authorization_service",
        "legacykeystore_service",
        "keystore_maintenance_service",
        "keystore_metrics_service",
        "locksettings_key",
        "keystore2_key",
    )
    if any(name in serialized for name in forbidden_types):
        fail("context shim imported a TWRP-only policy type")


def verify_package(output: Path) -> dict[str, object]:
    manifest_path = output / "MANIFEST.json"
    sums_path = output / "SHA256SUMS"
    if not manifest_path.is_file() or not sums_path.is_file():
        fail("package manifest/hash list is missing")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("format") != 1:
        fail("unsupported package manifest format")
    verify_context_shim(output, manifest)
    install_root = output / "install-root"
    executable_path = install_root / PurePosixPath(TARGET_EXECUTABLE)
    linker_path = install_root / PurePosixPath(TARGET_LINKER)
    executable = parse_elf(executable_path)
    linker = parse_elf(linker_path)
    if executable.bits != 64 or executable.interpreter != PRIVATE_INTERPRETER:
        fail("packaged keystore2 is not an ELF64 private-runtime executable")
    if linker.bits != 64 or linker.interpreter is not None:
        fail("packaged private linker is invalid")
    if (linker.encoding, linker.machine) != (executable.encoding, executable.machine):
        fail("packaged linker ABI does not match keystore2")

    library_root = install_root / PurePosixPath(TARGET_LIBRARY_DIRECTORY)
    libraries: dict[str, ElfInfo] = {}
    for path in sorted(library_root.glob("*"), key=lambda item: item.name):
        if not path.is_file() or PurePosixPath(path.name).name != path.name:
            fail(f"invalid private library path: {path}")
        parsed = parse_elf(path)
        if parsed.interpreter is not None or parsed.bits != 64:
            fail(f"invalid private library: {path.name}")
        libraries[path.name] = parsed
    selected: set[str] = set()
    queue = deque(executable.needed)
    while queue:
        name = queue.popleft()
        if name in selected:
            continue
        parsed = libraries.get(name)
        if parsed is None:
            fail(f"packaged recursive dependency is missing: {name}")
        selected.add(name)
        queue.extend(parsed.needed)
    extras = sorted(set(libraries) - selected)
    if extras:
        fail(f"private library directory has non-closure files: {extras}")

    private_libbinder_path = library_root / "libbinder.so"
    if not private_libbinder_path.is_file():
        fail("packaged private closure does not contain libbinder.so")
    private_libbinder_data = private_libbinder_path.read_bytes()
    private_libbinder_sha256 = sha256(private_libbinder_data)
    if BINDER_COMPATIBILITY_MARKER.encode("ascii") not in private_libbinder_data:
        fail("packaged private libbinder lacks the V5.2 SDK30 stability bridge")
    if private_libbinder_sha256 == UNPATCHED_V51_LIBBINDER_SHA256:
        fail("packaged private libbinder is still the unpatched V5.1 binary")
    binder_manifest = manifest.get("runtime", {}).get("binder_compatibility")
    if not isinstance(binder_manifest, dict):
        fail("manifest lacks V5.2 Binder compatibility attestation")
    if (
        binder_manifest.get("marker") != BINDER_COMPATIBILITY_MARKER
        or binder_manifest.get("pinned_frameworks_native_commit")
        != PINNED_FRAMEWORKS_NATIVE_COMMIT
        or binder_manifest.get("private_libbinder_sha256") != private_libbinder_sha256
        or binder_manifest.get("wire_format")
        != "SDK30 raw stability values on kernel Binder only"
        or binder_manifest.get("binder_rpc_format")
        != "Android 12.1 packed Category preserved"
        or binder_manifest.get("stock_libbinder_action") != "preserve-byte-for-byte"
    ):
        fail("manifest V5.2 Binder compatibility attestation is not exact")

    service_path = install_root / PurePosixPath(TARGET_INIT)
    verify_service(service_path.read_text(encoding="utf-8"))
    validate_vintf((install_root / PurePosixPath(TARGET_VINTF)).read_bytes())
    if (install_root / "reference-contexts").exists():
        fail("reference context material escaped into install-root")
    if not (output / "reference-contexts" / "README.txt").is_file():
        fail("reference context segregation warning is missing")

    actual_rows = listed_files(output, {"MANIFEST.json", "SHA256SUMS"})
    expected_rows = manifest.get("files")
    if actual_rows != expected_rows:
        fail("manifest file inventory/hash mismatch")
    expected_sums = "".join(f"{row['sha256']}  {row['path']}\n" for row in actual_rows)
    if sums_path.read_text(encoding="ascii") != expected_sums:
        fail("SHA256SUMS mismatch")
    manifest_library_names = {row["needed_name"] for row in manifest["runtime"]["libraries"]}
    if manifest_library_names != selected:
        fail("manifest recursive closure differs from packaged closure")
    return {
        "files": len(actual_rows),
        "libraries": len(selected),
        "bytes": sum(int(row["bytes"]) for row in actual_rows),
        "keystore2_sha256": file_sha256(executable_path),
        "private_libbinder_sha256": private_libbinder_sha256,
        "binder_stability_v0_bridge": True,
        "all_recursive_dependencies_present": True,
        "no_extra_private_libraries": True,
        "service_disabled": True,
        "reference_contexts_not_installable": True,
        "minimal_context_shim_exact": True,
        "context_shim_target_mode": "0644",
        "context_shim_companion_patch_mandatory": True,
        "keystore_database_directories_created_on_init": True,
    }


def build_package(recovery_root: Path, output: Path, epoch: int) -> dict[str, object]:
    recovery_root = recovery_root.resolve()
    output = output.resolve()
    if not recovery_root.is_dir():
        fail(f"recovery root is not a directory: {recovery_root}")
    if output.exists():
        fail(f"output already exists: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    temp_path = Path(tempfile.mkdtemp(prefix=f".{output.name}.tmp-", dir=output.parent))
    try:
        install_root = temp_path / "install-root"
        source_executable_path = recovery_root / PurePosixPath(SOURCE_EXECUTABLE)
        executable = parse_elf(source_executable_path)
        if executable.bits != 64:
            fail(f"expected ELF64 keystore2, found ELF{executable.bits}")
        patched, patch_record = patch_interpreter(source_executable_path, executable)
        target_executable_path = install_root / PurePosixPath(TARGET_EXECUTABLE)
        write_file(target_executable_path, patched, 0o755)
        reparsed = parse_elf(target_executable_path)
        if reparsed.interpreter != PRIVATE_INTERPRETER:
            fail("PT_INTERP relocation did not survive output write")

        source_linker_relative = executable.interpreter.lstrip("/") if executable.interpreter else ""
        source_linker_path = recovery_root / PurePosixPath(source_linker_relative)
        linker = parse_elf(source_linker_path)
        if linker.bits != 64 or linker.interpreter is not None:
            fail("source linker64 is not a standalone ELF64 linker")
        if (linker.encoding, linker.machine) != (executable.encoding, executable.machine):
            fail("source linker64 ABI does not match keystore2")
        linker_data = source_linker_path.read_bytes()
        write_file(install_root / PurePosixPath(TARGET_LINKER), linker_data, 0o755)

        selected = resolve_closure(recovery_root, executable)
        private_libbinder = selected.get("libbinder.so")
        if private_libbinder is None:
            fail("keystore2 private closure does not contain libbinder.so")
        private_libbinder_data = private_libbinder.source_path.read_bytes()
        private_libbinder_sha256 = sha256(private_libbinder_data)
        if BINDER_COMPATIBILITY_MARKER.encode("ascii") not in private_libbinder_data:
            fail("built private libbinder lacks the V5.2 SDK30 stability bridge")
        if private_libbinder_sha256 == UNPATCHED_V51_LIBBINDER_SHA256:
            fail("built private libbinder still matches the unpatched V5.1 binary")
        library_rows = []
        for name in sorted(selected):
            item = selected[name]
            data = item.source_path.read_bytes()
            target_relative = f"{TARGET_LIBRARY_DIRECTORY}/{name}"
            write_file(install_root / PurePosixPath(target_relative), data, 0o644)
            library_rows.append(
                {
                    "needed_name": name,
                    "source": item.source_relative,
                    "target": target_relative,
                    "bytes": len(data),
                    "sha256": sha256(data),
                    "soname": item.elf.soname,
                    "direct_needed": list(item.elf.needed),
                    "requested_by": sorted(item.requested_by),
                    "lower_priority_alternatives": list(item.alternatives),
                }
            )

        service_data = SERVICE_TEXT.encode("utf-8")
        verify_service(SERVICE_TEXT)
        write_file(install_root / PurePosixPath(TARGET_INIT), service_data, 0o644)
        vintf_record = copy_vintf(recovery_root, install_root)
        reference_records = write_reference_contexts(recovery_root, temp_path)
        context_shim = write_context_shim(temp_path)
        write_file(temp_path / "README.txt", TOP_README.encode("utf-8"), 0o644)

        manifest = {
            "format": 1,
            "name": "guacamole-h40-v52-private-keystore2-runtime",
            "source_layout": "built recovery/root",
            "runtime": {
                "executable": {
                    "source": SOURCE_EXECUTABLE,
                    "target": TARGET_EXECUTABLE,
                    "bytes": len(patched),
                    "direct_needed": list(executable.needed),
                    **patch_record,
                },
                "linker": {
                    "source": source_linker_relative,
                    "target": TARGET_LINKER,
                    "bytes": len(linker_data),
                    "sha256": sha256(linker_data),
                    "interpreter": None,
                },
                "libraries": library_rows,
                "binder_compatibility": {
                    "marker": BINDER_COMPATIBILITY_MARKER,
                    "pinned_frameworks_native_commit": PINNED_FRAMEWORKS_NATIVE_COMMIT,
                    "private_libbinder_sha256": private_libbinder_sha256,
                    "wire_format": "SDK30 raw stability values on kernel Binder only",
                    "binder_rpc_format": "Android 12.1 packed Category preserved",
                    "stock_libbinder_action": "preserve-byte-for-byte",
                },
                "init_service": {
                    "target": TARGET_INIT,
                    "name": "keystore2",
                    "executable": "/system/tw/bin/keystore2",
                    "database_directory": "/tmp/misc/keystore",
                    "database_directory_init": [
                        "mkdir /tmp/misc",
                        "mkdir /tmp/misc/keystore/",
                    ],
                    "disabled": True,
                    "seclabel": "u:r:recovery:s0",
                    "automatic_start_trigger": False,
                    "bytes": len(service_data),
                    "sha256": sha256(service_data),
                },
                "vintf": vintf_record,
            },
            "reference_contexts": {
                "install": False,
                "directory": "reference-contexts",
                "warning": "Reference evidence only; never overlay these files onto stock ColorOS policy.",
                "files": reference_records,
            },
            "compatibility_context_shim": context_shim,
            "integration_preconditions": [
                "/system/tw/bin selects /system/tw/lib64 in the active linker configuration",
                "no duplicate init service named keystore2 remains in the merged ramdisk",
                "stock compiled sepolicy and context files remain authoritative",
                "VINTF declaration is merged without creating a duplicate HAL instance",
                "init creates /tmp/misc/keystore before credential-time keystore2 start",
                f"context shim is installed only with companion marker {COMPANION_PERMISSION_PATCH}",
                f"private libbinder contains marker {BINDER_COMPATIBILITY_MARKER}",
                "stock /system/lib64/libbinder.so is preserved byte-for-byte",
            ],
            "known_risks": [
                "The daemon comes from the TWRP 12.1 build, while the tested installed port reports Android 14; persistent.sqlite compatibility remains device-test-gated.",
                "A binary-marker audit found the same from_0_to_1 migration generation and no from_1_to_2/state-column marker in both compared daemons, reducing but not proving away the database-version risk.",
                "The installed-system daemon fallback is intentionally inactive because a prefixed read-only mount does not reproduce Android linker namespaces, APEXes, absolute paths, policy, or verified-boot provenance.",
            ],
            "checks": {
                "elf64_only": True,
                "matching_linker_abi": True,
                "pt_interp_only_relocation": True,
                "exact_recursive_dt_needed_closure": True,
                "disabled_explicit_start_service": True,
                "recovery_domain_service": True,
                "reference_contexts_non_installable": True,
                "minimal_stock_type_context_shim": True,
                "context_shim_companion_patch_mandatory": True,
                "binder_stability_v0_bridge": True,
                "stock_libbinder_preservation_mandatory": True,
                "keystore_database_directories_created_on_init": True,
            },
        }
        inventory = listed_files(temp_path, {"MANIFEST.json", "SHA256SUMS"})
        manifest["files"] = inventory
        manifest_data = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
        write_file(temp_path / "MANIFEST.json", manifest_data, 0o644)
        sums_data = "".join(f"{row['sha256']}  {row['path']}\n" for row in inventory).encode("ascii")
        write_file(temp_path / "SHA256SUMS", sums_data, 0o644)
        normalize_mtimes(temp_path, epoch)
        verification = verify_package(temp_path)
        temp_path.replace(output)
        return verification
    except Exception:
        shutil.rmtree(temp_path, ignore_errors=True)
        raise


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--recovery-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--source-date-epoch",
        type=int,
        default=int(os.environ.get("SOURCE_DATE_EPOCH", "0")),
        help="mtime applied to every output path (default: SOURCE_DATE_EPOCH or 0)",
    )
    args = parser.parse_args()
    if args.source_date_epoch < 0:
        fail("SOURCE_DATE_EPOCH must be non-negative")
    try:
        report = build_package(args.recovery_root, args.output, args.source_date_epoch)
    except PackageError as exc:
        raise SystemExit(f"error: {exc}") from exc
    print(json.dumps(report, sort_keys=True))


if __name__ == "__main__":
    main()
